function normalize(name) {
  return String(name || "").trim().toLowerCase();
}

function getDepartmentForDisease(diseaseName) {
  const key = normalize(diseaseName);
  if (EXACT_OVERRIDES[key]) return EXACT_OVERRIDES[key];
  for (const rule of KEYWORD_RULES) {
    if (rule.test.test(key)) return rule.dept;
  }
  return DEPARTMENTS.GENERAL_PHYSICIAN;
}

