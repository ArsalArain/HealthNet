def get_specialist_for_disease(disease_name: str) -> str:
    """
    Returns the standard department name for a given disease.
    Matches against EXACT_OVERRIDES first, then keyword patterns, then defaults to General Physician.
    """
    if not disease_name:
        return D["GENERAL_PHYSICIAN"]
    
    key = str(disease_name).strip().lower()
    
    # 1. Exact match
    if key in EXACT_OVERRIDES:
        return EXACT_OVERRIDES[key]
    
    # 2. Keyword pattern match
    for pattern, dept in KEYWORD_RULES:
        if pattern.search(key):
            return dept
    
    # 3. Default
    return D["GENERAL_PHYSICIAN"]
